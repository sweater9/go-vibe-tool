// Builds knowledge/relations.json: typed, validated links between Knowledge guides.
//   node knowledge/src/build-relations.mjs          write knowledge/relations.json
//   node knowledge/src/build-relations.mjs --check  fail if the committed file is stale
//
// Sources (all already in the repo): ontology-v3.json prerequisites and related_concepts, search-index.json
// `related`, and the ordered learning paths in search-index.json. Nothing is invented: every edge comes from one of them.
//   pre   guides to read first (ontology prerequisites). Acyclic: an edge that would close a loop is dropped.
//   next  guides that build on this one: the inverse of `pre`, then the step after it on a learning path.
//   cmp   comparison guides that involve this one.
//   app   related guides from the building / practice groups.
//   rel   other related guides, in both directions, excluding anything already typed above.
import { readFileSync, writeFileSync } from "node:fs";

const here = (p) => new URL("../" + p, import.meta.url);
const index = JSON.parse(readFileSync(here("search-index.json"), "utf8"));
const ontology = JSON.parse(readFileSync(here("ontology-v3.json"), "utf8"));
const pages = index.pages;
const ids = new Set(pages.map((p) => p.id));
const byId = new Map(pages.map((p) => [p.id, p]));
const order = new Map(pages.map((p, i) => [p.id, i]));
const onto = new Map(ontology.entities.map((e) => [e.id, e]));
const PRACTICAL = new Set(["Building", "Python", "JavaScript", "Integrations", "Interfaces", "Frameworks", "Agent & RAG Patterns", "Structured Generation", "Developer infrastructure"]);
// Products and frameworks are lateral moves, not the next concept to learn, so they sort after concept guides.
const LATERAL = new Set(["AI ecosystem", "Frameworks", "Agent Protocols, Frameworks & Runtimes", "Integrations", "Microsoft 365", "Cloud"]);
const MAX = { pre: 4, next: 6, cmp: 3, app: 3, rel: 6 };

const uniq = (list) => [...new Set(list)];
const valid = (id, self) => ids.has(id) && id !== self;

// pre: ontology prerequisites that are real pages, then drop any edge that would make a cycle
const pre = new Map(pages.map((p) => [p.id, uniq(((onto.get(p.id) || {}).prerequisites || []).filter((x) => valid(x, p.id)))]));
const reaches = (from, target, seen = new Set()) => {
  if (from === target) return true;
  if (seen.has(from)) return false;
  seen.add(from);
  return (pre.get(from) || []).some((x) => reaches(x, target, seen));
};
const droppedCycles = [];
for (const p of pages) {
  const kept = [];
  for (const q of pre.get(p.id)) {
    pre.set(p.id, kept); // temporarily judge against the edges kept so far
    if (reaches(q, p.id)) droppedCycles.push(p.id + " -> " + q);
    else kept.push(q);
  }
  pre.set(p.id, kept);
}

// next: guides whose ontology prerequisites include this one come first (evidence of "builds on"); the step after this
// one on a learning path only fills what is left, and never points back at a prerequisite.
const next = new Map(pages.map((p) => [p.id, []]));
for (const [id, list] of pre) for (const q of list) next.get(q).push(id);
const pathNext = new Map();
for (const path of index.paths || []) {
  const steps = (path.steps || []).filter((s) => ids.has(s));
  steps.forEach((s, i) => { if (steps[i + 1]) (pathNext.get(s) || pathNext.set(s, []).get(s)).push(steps[i + 1]); });
}
const lateral = (id) => LATERAL.has(byId.get(id).group);
const sortNext = (id, list) => uniq(list).sort((a, b) => (lateral(a) - lateral(b)) || (order.get(a) - order.get(b)));
const nextOf = new Map();
for (const p of pages) {
  const inverse = sortNext(p.id, next.get(p.id));
  const fill = (pathNext.get(p.id) || []).filter((n) => !inverse.includes(n) && !reaches(p.id, n));
  nextOf.set(p.id, [...inverse, ...fill]);
}

const related = new Map(pages.map((p) => [p.id, new Set([...(p.related || []), ...(((onto.get(p.id) || {}).related_concepts) || [])].filter((x) => valid(x, p.id)))]));
for (const [id, set] of [...related]) for (const x of set) related.get(x).add(id); // undirected for discovery

const relations = {};
for (const p of pages) {
  const id = p.id;
  const typed = new Set([id, ...pre.get(id)]);
  const nx = nextOf.get(id).filter((x) => byId.get(x).type !== "comparison").slice(0, MAX.next);
  nx.forEach((x) => typed.add(x));
  const rels = [...related.get(id)].sort((a, b) => order.get(a) - order.get(b));
  const cmp = (p.type === "comparison" ? [] : rels.filter((x) => !typed.has(x) && byId.get(x).type === "comparison")).slice(0, MAX.cmp);
  cmp.forEach((x) => typed.add(x));
  const app = rels.filter((x) => !typed.has(x) && PRACTICAL.has(byId.get(x).group)).slice(0, MAX.app);
  app.forEach((x) => typed.add(x));
  const rel = rels.filter((x) => !typed.has(x)).slice(0, MAX.rel);
  relations[id] = { pre: pre.get(id).slice(0, MAX.pre), next: nx, cmp, app, rel };
}

const out = {
  version: 1,
  note: "Generated by knowledge/src/build-relations.mjs from ontology-v3.json, search-index.json related and learning paths. pre/next are acyclic. Do not edit by hand.",
  generated: { pages: pages.length, droppedCycleEdges: droppedCycles },
  pages: relations
};
const text = JSON.stringify(out, null, 1) + "\n";
const file = here("relations.json");
if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(file, "utf8"); } catch {}
  if (current !== text) { console.error("knowledge/relations.json is stale: run node knowledge/src/build-relations.mjs"); process.exit(1); }
  console.log("relations.json is current");
} else {
  writeFileSync(file, text);
  console.log("relations.json written:", pages.length, "pages;", droppedCycles.length, "cycle edges dropped");
}
