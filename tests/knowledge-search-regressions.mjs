// Regression tests for the V3 release-gate search fixes. No network, no browser.
// Uses the committed index and lexicon. Each case documents why it exists; none lowers a threshold.
import { readFileSync, existsSync } from "node:fs";
import { searchKnowledge } from "../knowledge/search-core.mjs";

const K = (p) => new URL("../knowledge/" + p, import.meta.url);
const read = (p) => readFileSync(K(p), "utf8");
const index = JSON.parse(read("search-index.json"));
const lexicon = JSON.parse(read("search-lexicon.json"));
const failures = [];
const need = (ok, msg) => { if (!ok) failures.push(msg); };

// 1. Ranking regressions caused by the ten pages added in the final expansion (2 top-1, 8 top-3 in the frozen sets).
// `top1` = expected page must be first; `top3` = expected page must appear in the first three.
const ranking = [
  { q: "which framework for a production agent", top1: ["choosing-an-agent-framework", "agent-frameworks-compared", "langgraph"] },
  { q: "planner and worker agents", top1: ["multi-agent-systems", "agent-planning", "agentic-workflows"] },
  { q: "microsoft framework where agents chat with each other to solve tasks", top1: ["autogen"] },
  { q: "io aware exact attention kernel that avoids materialising the full matrix", top3: ["flash-attention"] },
  { q: "a planner agent hands work to a researcher agent and a writer agent", top3: ["multi-agent-systems"] },
  { q: "standard for agents from different vendors to delegate tasks to each other", top3: ["a2a-protocol", "agent-protocol-landscape"] },
  { q: "what permissions should an email reading agent have", top3: ["integration-permissions", "gmail-for-ai-agents", "oauth-for-ai-agents"] },
  { q: "how would agents from different vendors collaborate", top3: ["a2a-protocol", "agent-protocol-landscape"] },
  { q: "a more efficient sequence layer than attention for very long inputs", top3: ["state-space-models"] },
  { q: "how to coordinate a researcher agent and a writer agent", top3: ["multi-agent-systems", "agentic-workflows"] }
];
for (const c of ranking) {
  const r = searchKnowledge(index, lexicon, c.q);
  const ids = r.ranked.map((x) => x.page.id);
  if (c.top1) need(c.top1.includes(ids[0]), "top-1: '" + c.q + "' expected one of " + c.top1.join("|") + ", got " + ids[0]);
  if (c.top3) need(c.top3.some((id) => ids.slice(0, 3).includes(id)), "top-3: '" + c.q + "' expected one of " + c.top3.join("|") + ", got " + ids.slice(0, 3).join(", "));
}

// 2. Gmail: the agent query must answer with the Gmail integration page, not the generic agent page.
for (const q of ["how do I connect an AI agent to Gmail", "connect an agent to Gmail", "How can an AI agent access Gmail?"]) {
  const r = searchKnowledge(index, lexicon, q);
  need(r.solid && r.answer.page.id === "gmail-for-ai-agents", "gmail: '" + q + "' should answer gmail-for-ai-agents, got " + r.answer?.page.id);
}
// Accepted learn-more result: the Gmail scopes page and OAuth page stay reachable from the Gmail agent answer.
{
  const r = searchKnowledge(index, lexicon, "How can an AI agent access Gmail?");
  const learn = r.learnMore.map((x) => x.page.id);
  need(learn.includes("gmail-api-scopes-and-verification") && learn.includes("oauth-for-ai-agents"), "gmail learn-more must keep scopes + oauth pages, got " + learn.join(", "));
}
for (const q of ["is gmail.readonly a restricted scope", "gmail restricted scopes security assessment", "can I use gmail data to train a model"]) {
  const r = searchKnowledge(index, lexicon, q);
  need(r.solid && r.answer.page.id === "gmail-api-scopes-and-verification", "gmail scopes: '" + q + "' should answer gmail-api-scopes-and-verification, got " + r.answer?.page.id);
}

// 3. MCP authorization queries surface mcp-authorization; neighbouring MCP/OAuth queries keep their answers.
for (const q of ["mcp authorization", "how does oauth work for mcp servers", "oauth for mcp servers", "how do I add OAuth to an MCP server", "what is protected resource metadata", "mcp token passthrough"]) {
  const r = searchKnowledge(index, lexicon, q);
  need(r.solid && r.answer.page.id === "mcp-authorization", "mcp auth: '" + q + "' should answer mcp-authorization, got " + r.answer?.page.id);
}
const keep = [
  ["What is MCP?", "mcp"], ["How is MCP different from an API?", "mcp-vs-api"], ["function calling vs MCP", "function-calling-vs-mcp"],
  ["how to secure an mcp server", "mcp-security"], ["is mcp safe to install", "mcp-security"], ["mcp or a2a", "a2a-vs-mcp"],
  ["What is OAuth?", "oauth"], ["How does OAuth work for AI agents?", "oauth-for-ai-agents"]
];
for (const [q, id] of keep) {
  const r = searchKnowledge(index, lexicon, q);
  need(r.solid && r.answer.page.id === id, "unchanged: '" + q + "' should still answer " + id + ", got " + r.answer?.page.id);
}

// 4. Legacy Hugging Face URL redirects, and the redirect is generated by the build (survives rebuilds).
{
  const stub = read("hugging-face-transformers.html");
  need(/<meta http-equiv="refresh" content="0; url=hugging-face\.html">/.test(stub), "redirect stub needs a meta refresh to hugging-face.html");
  need(/<link rel="canonical" href="https:\/\/intellitools\.online\/knowledge\/hugging-face\.html">/.test(stub), "redirect stub needs a canonical link to the target");
  need(/location\.replace\("hugging-face\.html" \+ location\.search \+ location\.hash\)/.test(stub), "redirect stub should preserve query and hash");
  need(existsSync(K("hugging-face.html")), "redirect target page missing");
  need(!index.pages.some((p) => p.id === "hugging-face-transformers"), "redirect source must not be a searchable page");
  need(!read("sitemap-fragment.xml").includes("hugging-face-transformers.html"), "redirect source must not be in the sitemap");
  const build = readFileSync(new URL("../knowledge/src/build.mjs", import.meta.url), "utf8");
  need(/REDIRECTS\s*=\s*\{[^}]*'hugging-face-transformers':\s*'hugging-face'/.test(build), "build.mjs must declare the redirect so rebuilds regenerate the stub");
}

if (failures.length) { console.error("FAILURES (" + failures.length + "):\n" + failures.join("\n")); process.exit(1); }
console.log("search regression checks passed (" + ranking.length + " ranking, gmail, mcp authorization, unchanged neighbours, redirect)");
